    // Returns the Arabic version of a condition when the page is in Arabic
    public static Condition Localize(Condition c, bool rtl)
    {
        if (!rtl || !Map.TryGetValue(c.Slug, out var a)) return c;
        return new Condition
        {
            Slug = c.Slug,
            Icon = c.Icon,
            Urgent = c.Urgent,
            Name = a.Name,
            Summary = a.Summary,
            Overview = a.Overview,
            Signs = a.Signs,
            Causes = a.Causes,
            Treatment = a.Treatment,
            SelfHelp = a.SelfHelp,
            Support = a.Support,
            SeekHelp = a.SeekHelp
        };
    }

    public static Condition? Find(string slug, bool rtl)
    {
        var c = ConditionData.Find(slug);
        return c == null ? null : Localize(c, rtl);
    }

